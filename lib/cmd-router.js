'use strict';

// router: provenance + routing tables, generated from the manifest and sources config only.
// The picked files themselves are never modified (that would break hash tracking).
// - skills/SOURCES.md (under claudeHome) — provenance of every installed skill/command/agent.
// - docs/SKILL-ROUTER.md (in this repo)  — same table + skill-description trigger check.

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { CUSTOM_SRC, loadManifest, entryDest, isDirPath } = require('./manifest');
const { sourceRoot } = require('./sources');
const { ensureParent } = require('./fsutil');

const TRACKED_PREFIXES = ['skills/', 'commands/', 'agents/'];
const WEAK_DESCRIPTION_MIN_CHARS = 30;
const GENERATED_NOTE = '<!-- generated by myclaude.js — do not edit; regenerate with `node myclaude.js router` -->';

function repoUrl(ctx) {
  try {
    return execFileSync('git', ['config', '--get', 'remote.origin.url'], { cwd: ctx.repoRoot, encoding: 'utf8' })
      .trim().replace(/\.git$/, '');
  } catch {
    return '(local custom/)';
  }
}

function entryKind(e) {
  if (e.src !== CUSTOM_SRC) return 'picked';
  return e.forkedFrom ? 'forked' : 'custom';
}

function provenanceRows(ctx, m) {
  const customRepo = repoUrl(ctx);
  return m.entries
    .filter((e) => TRACKED_PREFIXES.some((p) => entryDest(e).startsWith(p)))
    .map((e) => ({
      dest: entryDest(e),
      repo: e.src === CUSTOM_SRC ? customRepo : ((m.sources[e.src] || {}).repo || '?').replace(/\.git$/, ''),
      srcPath: `${e.src}:${e.path}`,
      sha: e.src === CUSTOM_SRC ? '-' : ((m.sources[e.src] || {}).sha || '(unpinned)').slice(0, 12),
      kind: entryKind(e),
    }));
}

function mdTable(header, rows) {
  const esc = (c) => String(c).replace(/\|/g, '\\|');
  const lines = [`| ${header.join(' | ')} |`, `|${header.map(() => '---').join('|')}|`];
  for (const r of rows) lines.push(`| ${r.map(esc).join(' | ')} |`);
  return lines.join('\n');
}

function provenanceTable(ctx, m) {
  const rows = provenanceRows(ctx, m).map((r) => [r.dest, r.repo, r.srcPath, r.sha, r.kind]);
  return mdTable(['installed', 'source repo', 'source path', 'pinned sha', 'kind'], rows);
}

function sourcesMd(ctx, m) {
  return `${GENERATED_NOTE}\n\n# Installed config provenance\n\nEvery skill/command/agent installed into ~/.claude by myclaude.\nUpdate flow: src update → diff → accept → sync.\n\n${provenanceTable(ctx, m)}\n`;
}

function writeSourcesFile(ctx, m, log) {
  const p = path.join(ctx.claudeHome, 'skills', 'SOURCES.md');
  ensureParent(p);
  fs.writeFileSync(p, sourcesMd(ctx, m));
  log(`  wrote ${p}`);
}

// skill name -> path of its SKILL.md in the SOURCE tree (never the installed copy).
function skillFiles(ctx, m) {
  const out = new Map();
  for (const e of m.entries) {
    const dest = entryDest(e);
    if (!dest.startsWith('skills/')) continue;
    const name = dest.split('/')[1];
    if (isDirPath(e.path)) out.set(name, path.join(sourceRoot(ctx, m, e.src), e.path, 'SKILL.md'));
    else if (path.basename(e.path) === 'SKILL.md') out.set(name, path.join(sourceRoot(ctx, m, e.src), e.path));
  }
  return out;
}

// First-line or block-scalar (| / >) `description:` value from YAML frontmatter.
function frontmatterDescription(file) {
  if (!fs.existsSync(file)) return '';
  const lines = fs.readFileSync(file, 'utf8').split('\n');
  if (lines[0].trim() !== '---') return '';
  for (let i = 1; i < lines.length && lines[i].trim() !== '---'; i++) {
    const match = lines[i].match(/^description:\s*(.*)$/);
    if (!match) continue;
    let value = match[1].trim();
    if (/^[>|][+-]?$/.test(value)) {
      const block = [];
      for (let j = i + 1; j < lines.length && /^\s+\S/.test(lines[j]); j++) block.push(lines[j].trim());
      value = block.join(' ');
    }
    return value.replace(/^['"]|['"]$/g, '');
  }
  return '';
}

function routerRows(ctx, m) {
  return [...skillFiles(ctx, m)].map(([name, file]) => {
    const desc = frontmatterDescription(file);
    const weak = desc.length < WEAK_DESCRIPTION_MIN_CHARS;
    return [name, desc || '(none)', weak ? 'weak trigger — consider rewriting' : 'ok'];
  });
}

function routerMd(ctx, m) {
  return `${GENERATED_NOTE}\n\n# Skill router\n\n## Provenance\n\n${provenanceTable(ctx, m)}\n\n## Skill descriptions (routing triggers)\n\n${mdTable(['skill', 'description', 'trigger check'], routerRows(ctx, m))}\n`;
}

function cmdRouter(ctx, args, log) {
  const m = loadManifest(ctx);
  writeSourcesFile(ctx, m, log);
  const p = path.join(ctx.repoRoot, 'docs', 'SKILL-ROUTER.md');
  ensureParent(p);
  fs.writeFileSync(p, routerMd(ctx, m));
  log(`  wrote ${p}`);
}

module.exports = { cmdRouter, writeSourcesFile, provenanceRows, frontmatterDescription, sourcesMd, routerMd };
